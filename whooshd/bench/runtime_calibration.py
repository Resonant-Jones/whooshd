# ── Constants ──────────────────────────────────────────────────────────────

DEFAULT_BANDS = (1, 2, 3, 4)
DEFAULT_REQUESTS_PER_BAND = 8
DEFAULT_TIMEOUT_SECONDS = 180.0
DEFAULT_MAX_TOKENS = 128

#: Synthetic prompt body.  Long enough to produce measurable prefill cost
#: without being large enough to dominate the report.
_PROMPT_BODY = (
    "You are a careful assistant. Summarise the following operational note in "
    "three short sentences, then state the single most important action item. "
    "The note describes a multi-tenant inference broker that admits requests "
    "against a bounded queue, schedules them FIFO, and records lifecycle "
    "metadata for every request without ever persisting prompt content. "
)


@dataclass
class BandEvidence:
    """Measured evidence for one active-concurrency band."""

    concurrency: int
    successful: bool = False
    request_count: int = 0
    success_count: int = 0
    overload_count: int = 0
    failure_count: int = 0
    stuck_count: int = 0

    ttft_p50_ms: Optional[float] = None
    ttft_p95_ms: Optional[float] = None
    latency_p50_ms: Optional[float] = None
    latency_p95_ms: Optional[float] = None
    prefill_p50_ms: Optional[float] = None

    aggregate_tokens_per_second: Optional[float] = None
    per_request_tokens_per_second: Optional[float] = None

    queue_latency_p50_ms: Optional[float] = None
    queue_latency_p95_ms: Optional[float] = None

    swap_used_pages_before: Optional[int] = None
    swap_used_pages_after: Optional[int] = None
    swap_delta_pages: Optional[int] = None
    swap_in_delta_pages: Optional[int] = None

    cache_hit_ratio: Optional[float] = None
    cached_prompt_tokens: Optional[int] = None

    notes: list[str] = field(default_factory=list)

    def safe_dict(self) -> dict[str, Any]:
        return {
            "concurrency": self.concurrency,
            "successful": self.successful,
            "request_count": self.request_count,
            "success_count": self.success_count,
            "overload_count": self.overload_count,
            "failure_count": self.failure_count,
            "stuck_count": self.stuck_count,
            "ttft_p50_ms": self.ttft_p50_ms,
            "ttft_p95_ms": self.ttft_p95_ms,
            "latency_p50_ms": self.latency_p50_ms,
            "latency_p95_ms": self.latency_p95_ms,
            "prefill_p50_ms": self.prefill_p50_ms,
            "aggregate_tokens_per_second": self.aggregate_tokens_per_second,
            "per_request_tokens_per_second": self.per_request_tokens_per_second,
            "queue_latency_p50_ms": self.queue_latency_p50_ms,
            "queue_latency_p95_ms": self.queue_latency_p95_ms,
            "swap_used_pages_before": self.swap_used_pages_before,
            "swap_used_pages_after": self.swap_used_pages_after,
            "swap_delta_pages": self.swap_delta_pages,
            "swap_in_delta_pages": self.swap_in_delta_pages,
            "cache_hit_ratio": self.cache_hit_ratio,
            "cached_prompt_tokens": self.cached_prompt_tokens,
            "notes": list(self.notes),
        }


@dataclass
class RequestOutcome:
    """Per-request measurement."""

    ok: bool = False
    status_code: int = 0
    ttft_ms: Optional[float] = None
    latency_ms: float = 0.0
    completion_tokens: Optional[int] = None
    prompt_tokens: Optional[int] = None
    cached_prompt_tokens: Optional[int] = None
    upstream_prefill_ms: Optional[float] = None
    accepted_at: Optional[float] = None
    started_at: Optional[float] = None
    error: Optional[str] = None


# ── Host metrics ───────────────────────────────────────────────────────────


def _swap_counters() -> Optional[dict[str, int]]:
    """Cumulative host swap counters, or None when they cannot be read.

    ``sysctl vm.swapusage`` is unavailable in some sandboxed sessions, but
    ``vm_stat`` reports cumulative ``Swapins``/``Swapouts`` page counts.
    Deltas across a band are the thrash signal: a band that swaps is a band
    that exceeded physical memory.
    """
    try:
        out = subprocess.run(
            ["vm_stat"], capture_output=True, text=True, timeout=10, check=False
        ).stdout
    except Exception:
        return None
    if not out:
        return None
    counters: dict[str, int] = {}
    for line in out.splitlines():
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip().lower()
        if key in ("swapins", "swapouts"):
            digits = value.strip().rstrip(".")
            try:
                counters[key] = int(digits)
            except ValueError:
                continue
    if "swapouts" not in counters:
        return None
    return counters


def _metal_status() -> dict[str, Any]:
    """Report whether this process can reach a Metal device.

    A calibration that cannot see the GPU is still useful when it is measured
    through a remote runtime, but the limitation must be recorded rather than
    hidden.
    """
    info: dict[str, Any] = {"metal_available": False, "detail": None}
    try:
        import mlx.core as mx  # type: ignore

        try:
            _ = mx.array([1.0])
            info["metal_available"] = True
            info["detail"] = str(mx.default_device())
        except Exception as exc:  # pragma: no cover - environment dependent
            info["detail"] = f"{type(exc).__name__}: {exc}"
    except Exception as exc:
        info["detail"] = f"mlx unavailable: {type(exc).__name__}"
    return info


# ── Helpers ────────────────────────────────────────────────────────────────


def _percentile(values: list[float], pct: float) -> Optional[float]:
    if not values:
        return None
    ordered = sorted(values)
    idx = max(0, min(len(ordered) - 1, int(math.ceil(pct / 100.0 * len(ordered))) - 1))
    return ordered[idx]


def _median(values: list[float]) -> Optional[float]:
    if not values:
        return None
    return statistics.median(values)


def _build_prompt(target_chars: int) -> str:
    """Synthetic prompt of approximately ``target_chars`` characters."""
    body = _PROMPT_BODY
    if target_chars <= len(body):
        return body[:target_chars]
    repeats = target_chars // len(body) + 1
    return (body * repeats)[:target_chars]


# ── Measurement ────────────────────────────────────────────────────────────


async def _measure_request(
    client: httpx.AsyncClient,
    *,
    base_url: str,
    model: str,
    prompt: str,
    max_tokens: int,
    timeout: float,
) -> RequestOutcome:
    """Measure one streaming request through the broker."""
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": prompt}],
        "stream": True,
        "max_tokens": max_tokens,
    }
    outcome = RequestOutcome()
    t0 = time.time()
    try:
        async with client.stream(
            "POST",
            f"{base_url}/v1/chat/completions",
            json=payload,
            timeout=timeout,
        ) as resp:
            outcome.status_code = resp.status_code
            outcome.accepted_at = time.time()
            ttft: Optional[float] = None
            async for line in resp.aiter_lines():
                if not line.startswith("data: "):
                    continue
                data = line[6:]
                if data == "[DONE]":
                    break
                try:
                    chunk = json.loads(data)
                except json.JSONDecodeError:
                    continue
                delta = (chunk.get("choices") or [{}])[0].get("delta") or {}
                if delta.get("content") and ttft is None:
                    ttft = (time.time() - t0) * 1000
                usage = chunk.get("usage")
                if usage:
                    outcome.completion_tokens = usage.get("completion_tokens")
                    outcome.prompt_tokens = usage.get("prompt_tokens")
        outcome.ttft_ms = ttft
        outcome.latency_ms = (time.time() - t0) * 1000
        outcome.ok = 200 <= outcome.status_code < 300
    except Exception as exc:
        outcome.latency_ms = (time.time() - t0) * 1000
        outcome.error = f"{type(exc).__name__}"
    return outcome


async def _measure_non_streaming_request(
    client: httpx.AsyncClient,
    *,
    base_url: str,
    model: str,
    prompt: str,
    max_tokens: int,
    timeout: float,
) -> RequestOutcome:
    """Measure one non-streaming request through the broker.

    The broker's streaming chunks do not carry usage, so token accounting
    comes from the non-streaming response, which does.  Throughput is
    therefore measured on this path and latency on the streaming path.
    """
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": max_tokens,
    }
    outcome = RequestOutcome()
    t0 = time.time()
    try:
        resp = await client.post(
            f"{base_url}/v1/chat/completions", json=payload, timeout=timeout
        )
        outcome.status_code = resp.status_code
        outcome.accepted_at = time.time()
        if 200 <= resp.status_code < 300:
            body = resp.json()
            usage = body.get("usage") or {}
            outcome.prompt_tokens = usage.get("prompt_tokens")
            outcome.completion_tokens = usage.get("completion_tokens")
            details = usage.get("prompt_tokens_details") or {}
            if details.get("cached_tokens") is not None:
                outcome.cached_prompt_tokens = details.get("cached_tokens")
        outcome.latency_ms = (time.time() - t0) * 1000
        outcome.ok = 200 <= resp.status_code < 300
    except Exception as exc:
        outcome.latency_ms = (time.time() - t0) * 1000
        outcome.error = f"{type(exc).__name__}"
    return outcome


async def _probe_upstream_cache(
    client: httpx.AsyncClient,
    *,
    upstream_url: str,
    upstream_model: str,
    prompt: str,
    max_tokens: int,
    timeout: float,
    repeats: int = 2,
) -> dict[str, Any]:
    """Read upstream-reported prefill and prompt-cache counters.

    The upstream runtime is the same process the broker forwards to, so its
    cache counters describe the deployment's cache.  Returns measured numbers
    only; no prompt or generated text is retained.
    """
    result: dict[str, Any] = {
        "attempts": 0,
        "cached_prompt_tokens": None,
        "prompt_tokens": None,
        "prefill_ms": None,
        "cache_hit_ratio": None,
        "available": False,
    }
    payload = {
        "model": upstream_model,
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": max_tokens,
        "stream": False,
    }
    cached_total = 0
    prompt_total = 0
    prefills: list[float] = []
    for _ in range(max(1, repeats)):
        try:
            resp = await client.post(
                f"{upstream_url}/v1/chat/completions", json=payload, timeout=timeout
            )
            result["attempts"] += 1
            body = resp.json()
            usage = body.get("usage") or {}
            details = usage.get("prompt_tokens_details") or {}
            cached = details.get("cached_tokens")
            ptotal = usage.get("prompt_tokens")
            timings = body.get("timings") or {}
            if cached is not None:
                cached_total += int(cached)
            if ptotal is not None:
                prompt_total += int(ptotal)
            if timings.get("prompt_ms") is not None:
                prefills.append(float(timings["prompt_ms"]))
        except Exception:
            continue
    if result["attempts"]:
        result["available"] = True
        result["cached_prompt_tokens"] = cached_total
        result["prompt_tokens"] = prompt_total
        if prefills:
            result["prefill_ms"] = _median(prefills)
        if prompt_total:
            result["cache_hit_ratio"] = round(cached_total / prompt_total, 6)
    return result


async def _read_runtime_state(client: httpx.AsyncClient, base_url: str) -> dict[str, Any]:
    """Read leak-detection counters from the broker's own surfaces."""
    state: dict[str, Any] = {"active_jobs": None, "queue_depth": None, "reachable": False}
    try:
        resp = await client.get(f"{base_url}/runtime/admission", timeout=15.0)
        if resp.status_code == 200:
            body = resp.json()
            state["active_jobs"] = body.get("active_jobs")
            state["queue_depth"] = body.get("queue_depth")
            state["reachable"] = True
    except Exception:
        pass
    return state


async def _run_band(
    client: httpx.AsyncClient,
    *,
    base_url: str,
    model: str,
    band: int,
    requests: int,
    prompt: str,
    max_tokens: int,
    timeout: float,
    upstream_url: Optional[str] = None,
    upstream_model: Optional[str] = None,
) -> tuple[BandEvidence, list[RequestOutcome]]:
    """Run one concurrency band and collect its evidence."""
    evidence = BandEvidence(concurrency=band)
    swap_before = _swap_counters()
    evidence.swap_used_pages_before = (
        swap_before.get("swapouts") if swap_before is not None else None
    )

    # Phase A -- streaming: time to first token and end-to-end latency.
    started = time.time()
    outcomes = await asyncio.gather(
        *(
            _measure_request(
                client,
                base_url=base_url,
                model=model,
                prompt=prompt,
                max_tokens=max_tokens,
                timeout=timeout,
            )
            for _ in range(requests)
        )
    )
    wall = max(time.time() - started, 1e-6)

    # Phase B -- non-streaming: token accounting for throughput.  The broker
    # does not attach usage to streaming chunks, so throughput is measured
    # on the path that reports it.
    token_outcomes = await asyncio.gather(
        *(
            _measure_non_streaming_request(
                client,
                base_url=base_url,
                model=model,
                prompt=prompt,
                max_tokens=max_tokens,
                timeout=timeout,
            )
            for _ in range(requests)
        )
    )

    evidence.request_count = requests
    ttfts: list[float] = []
    latencies: list[float] = []
    tokens = 0
    for outcome in outcomes:
        if outcome.ok:
            evidence.success_count += 1
            if outcome.ttft_ms is not None:
                ttfts.append(outcome.ttft_ms)
            latencies.append(outcome.latency_ms)
            if outcome.completion_tokens:
                tokens += outcome.completion_tokens
        elif outcome.status_code == 429:
            evidence.overload_count += 1
        elif outcome.error is not None:
            evidence.failure_count += 1
        else:
            evidence.failure_count += 1

    evidence.ttft_p50_ms = _percentile(ttfts, 50)
    evidence.ttft_p95_ms = _percentile(ttfts, 95)
    evidence.latency_p50_ms = _percentile(latencies, 50)
    evidence.latency_p95_ms = _percentile(latencies, 95)

    # Throughput comes from the non-streaming phase, which reports usage.
    token_total = 0
    token_requests = 0
    token_wall = 0.0
    cached_total = 0
    cached_known = False
    for outcome in token_outcomes:
        if outcome.ok and outcome.completion_tokens:
            token_total += outcome.completion_tokens
            token_requests += 1
            token_wall = max(token_wall, outcome.latency_ms)
            if outcome.cached_prompt_tokens is not None:
                cached_known = True
                cached_total += outcome.cached_prompt_tokens
    if token_requests:
        seconds = max(token_wall / 1000.0, 1e-6)
        evidence.aggregate_tokens_per_second = round(token_total / seconds, 3)
        evidence.per_request_tokens_per_second = round(
            token_total / token_requests / seconds, 3
        )
        if cached_known:
            evidence.cached_prompt_tokens = cached_total
    else:
        # No token counts were reported.  Leave the throughput fields unset
        # rather than reporting zero, which would read as a measurement.
        evidence.notes.append(
            "token usage unavailable from the runtime; throughput not measured"
        )
    evidence.successful = (
        evidence.success_count == requests
        and evidence.failure_count == 0
        and evidence.stuck_count == 0
    )

    swap_after = _swap_counters()
    evidence.swap_used_pages_after = (
        swap_after.get("swapouts") if swap_after is not None else None
    )
    if swap_before is not None and swap_after is not None:
        evidence.swap_delta_pages = (
            swap_after.get("swapouts", 0) - swap_before.get("swapouts", 0)
        )
        evidence.swap_in_delta_pages = (
            swap_after.get("swapins", 0) - swap_before.get("swapins", 0)
        )
        if evidence.swap_delta_pages > 0:
            evidence.notes.append("host swapped pages during this band")

    # Cache counters and prefill cost come from the upstream runtime, which is
    # the same process — and therefore the same prompt cache — that the broker
    # forwards to.  The broker's own response shape does not expose them.
    if upstream_url and upstream_model:
        probe = await _probe_upstream_cache(
            client,
            upstream_url=upstream_url,
            upstream_model=upstream_model,
            prompt=prompt,
            max_tokens=max_tokens,
            timeout=timeout,
        )
        evidence.cached_prompt_tokens = probe.get("cached_prompt_tokens")
        evidence.cache_hit_ratio = probe.get("cache_hit_ratio")
        evidence.prefill_p50_ms = probe.get("prefill_ms")

    return evidence, outcomes


# ── Report assembly ────────────────────────────────────────────────────────


def _build_report(
    *,
    base_url: str,
    upstream_url: Optional[str],
    model: str,
    bands: list[BandEvidence],
    cache_probe: dict[str, Any],
    rest_state: dict[str, Any],
    prompt_chars: int,
    max_tokens: int,
) -> dict[str, Any]:
    return {
        "schema_version": "whooshd.calibration.v1",
        "captured_at": datetime.now(timezone.utc).isoformat(),
        "host": {
            "platform": platform.platform(),
            "machine": platform.machine(),
            "python": platform.python_version(),
        },
        "target": {
            "base_url": base_url,
            "upstream_url": upstream_url,
            "model": model,
            "prompt_chars": prompt_chars,
            "max_tokens": max_tokens,
        },
        "metal": _metal_status(),
        "bands": [b.safe_dict() for b in bands],
        "cache_effectiveness": cache_probe,
        "leak_check": {
            "active_jobs_at_rest": rest_state.get("active_jobs"),
            "queue_depth_at_rest": rest_state.get("queue_depth"),
            "broker_reachable": rest_state.get("reachable"),
            "leaked": bool(
                (rest_state.get("active_jobs") or 0) > 0
                or (rest_state.get("queue_depth") or 0) > 0
            ),
        },
    }


def _render_markdown(report: dict[str, Any]) -> str:
    lines: list[str] = []
    add = lines.append
    add("# Runtime Calibration Report")
    add("")
    add(f"**Schema:** `{report['schema_version']}`  ")
    add(f"**Captured:** {report['captured_at']}  ")
    add(f"**Host:** {report['host']['platform']}  ")
    add(f"**Metal in harness process:** {report['metal']['metal_available']} "
        f"({report['metal']['detail']})")
    add("")
    add(f"**Target:** `{report['target']['base_url']}` model `{report['target']['model']}` "
        f"prompt {report['target']['prompt_chars']} chars, "
        f"max_tokens {report['target']['max_tokens']}")
    add("")
    add("## Concurrency bands")
    add("")
    add("| Band | OK | 429 | Fail | TTFT p50 | TTFT p95 | Lat p50 | Prefill p50 | "
        "Agg tok/s | Queue p50 | Swap Δ |")
    add("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")

    def fmt(value: Optional[float], suffix: str = "") -> str:
        if value is None:
            return "—"
        if suffix:
            return f"{value:.1f}{suffix}"
        return f"{value:.1f}"

    for band in report["bands"]:
        add(
            f"| x{band['concurrency']} | {band['success_count']}/{band['request_count']} "
            f"| {band['overload_count']} | {band['failure_count']} "
            f"| {fmt(band['ttft_p50_ms'])} | {fmt(band['ttft_p95_ms'])} "
            f"| {fmt(band['latency_p50_ms'])} | {fmt(band['prefill_p50_ms'])} "
            f"| {fmt(band['aggregate_tokens_per_second'])} "
            f"| {fmt(band['queue_latency_p50_ms'])} "
            f"| {band['swap_delta_pages'] if band['swap_delta_pages'] is not None else '—'} |"
        )
    add("")
    cache = report["cache_effectiveness"]
    add("## Cache effectiveness")
    add("")
    add(f"- Upstream cache counters available: **{cache['available']}**")
    add(f"- Cached prompt tokens: **{cache['cached_prompt_tokens']}**")
    add(f"- Prompt tokens: **{cache['prompt_tokens']}**")
    add(f"- Cache hit ratio: **{cache['cache_hit_ratio']}**")
    add(f"- Upstream-reported prefill (ms): **{cache['prefill_ms']}**")
    add("")
    leak = report["leak_check"]
    add("## Leak check (at rest)")
    add("")
    add(f"- `active_jobs` at rest: **{leak['active_jobs_at_rest']}**")
    add(f"- `queue_depth` at rest: **{leak['queue_depth_at_rest']}**")
    add(f"- Leaked work: **{leak['leaked']}**")
    add("")
    return "\n".join(lines)


# ── CLI ────────────────────────────────────────────────────────────────────


def _parse_args(argv: Optional[list[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="python -m whooshd.bench.runtime_calibration",
        description="Real-runtime calibration harness for a live Whoosh'd deployment.",
    )
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--upstream-url", default=None,
                        help="Upstream runtime base URL (for prefill/cache counters)")
    parser.add_argument("--upstream-model", default=None,
                        help="Model id understood by the upstream runtime")
    parser.add_argument("--model", default="local-chat")
    parser.add_argument("--bands", type=int, nargs="+", default=list(DEFAULT_BANDS))
    parser.add_argument("--requests", type=int, default=DEFAULT_REQUESTS_PER_BAND)
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT_SECONDS)
    parser.add_argument("--max-tokens", type=int, default=DEFAULT_MAX_TOKENS)
    parser.add_argument("--prompt-chars", type=int, default=2048)
    parser.add_argument("--output", default="runtime-calibration.json")
    parser.add_argument("--markdown", default=None, help="Optional markdown summary path")
    return parser.parse_args(argv)


def main(argv: Optional[list[str]] = None) -> int:
    args = _parse_args(argv)
    prompt = _build_prompt(args.prompt_chars)

    async def run() -> int:
        limits = httpx.Limits(max_connections=32, max_keepalive_connections=16)
        async with httpx.AsyncClient(limits=limits) as client:
            state = await _read_runtime_state(client, args.base_url)
            if not state.get("reachable"):
                print(
                    "BLOCKED: broker not reachable at "
                    f"{args.base_url}/runtime/admission",
                    file=sys.stderr,
                )
                return 2

            bands: list[BandEvidence] = []
            for band in args.bands:
                evidence, _ = await _run_band(
                    client,
                    base_url=args.base_url,
                    model=args.model,
                    band=band,
                    requests=args.requests,
                    prompt=prompt,
                    max_tokens=args.max_tokens,
                    timeout=args.timeout,
                    upstream_url=args.upstream_url,
                    upstream_model=args.upstream_model,
                )
                bands.append(evidence)
                print(
                    f"band x{band}: ok={evidence.success_count}/{evidence.request_count} "
                    f"ttft_p50={evidence.ttft_p50_ms} lat_p50={evidence.latency_p50_ms}",
                    file=sys.stderr,
                )

            cache_probe: dict[str, Any] = {"available": False}
            if args.upstream_url and args.upstream_model:
                cache_probe = await _probe_upstream_cache(
                    client,
                    upstream_url=args.upstream_url,
                    upstream_model=args.upstream_model,
                    prompt=prompt,
                    max_tokens=args.max_tokens,
                    timeout=args.timeout,
                )

            rest_state = await _read_runtime_state(client, args.base_url)

        report = _build_report(
            base_url=args.base_url,
            upstream_url=args.upstream_url,
            model=args.model,
            bands=bands,
            cache_probe=cache_probe,
            rest_state=rest_state,
            prompt_chars=len(prompt),
            max_tokens=args.max_tokens,
        )
        os.makedirs(os.path.dirname(os.path.abspath(args.output)) or ".", exist_ok=True)
        with open(args.output, "w", encoding="utf-8") as handle:
            json.dump(report, handle, indent=2, sort_keys=True)
            handle.write("\n")
        if args.markdown:
            os.makedirs(os.path.dirname(os.path.abspath(args.markdown)) or ".", exist_ok=True)
            with open(args.markdown, "w", encoding="utf-8") as handle:
                handle.write(_render_markdown(report))
        print(f"wrote {args.output}")
        return 0

    return asyncio.run(run())


