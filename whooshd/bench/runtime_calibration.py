"""Real-runtime calibration harness (roadmap P0).

Measures **real-runtime evidence** for a live Whoosh'd deployment.  This is the
measurement phase of the roadmap: nothing here changes inference behavior, and
no performance claim may be made without a report produced by this harness.

The harness deliberately reads the *deployment* rather than the process:

* Broker metrics (TTFT, end-to-end latency, queue latency, admission
  behaviour, lifecycle leak) are measured **through** Whoosh'd's HTTP surface.
* Runtime metrics (upstream-reported prefill cost, prompt-cache hit counts) are
  read from the upstream runtime that Whoosh'd forwards to.  It is the same
  server process and therefore the same cache, so the numbers describe the
  deployment rather than a synthetic copy of it.

Reported metrics per concurrency band:

===========================  ====================================================
Metric                       Source
===========================  ====================================================
``ttft_p50_ms``              first SSE content chunk, client-side
``ttft_p95_ms``              first SSE content chunk, client-side
``latency_p50_ms``           request start to terminal chunk
``prefill_p50_ms``           upstream-reported prefill (prompt_ms)
``aggregate_tokens_per_s``   generated tokens / band wall-clock
``per_request_tokens_per_s`` mean generated tokens/sec per request
``queue_latency_p50_ms``     accepted -> running, from lifecycle states
``swap_used_pages``          host swap delta across the band
``cache_hit_ratio``          upstream-reported cached prompt tokens / prompt
``leaked_jobs``              active_jobs / queue_depth at rest, after drain
===========================  ====================================================

Privacy: prompts are synthetic and generated by this module.  The report
contains counts, durations, and ratios only — never prompt text, generated
text, token identifiers, or KV state.

Usage::

    python -m whooshd.bench.runtime_calibration \\
        --base-url http://127.0.0.1:8000 \\
        --upstream-url http://127.0.0.1:8082 \\
        --model local-chat \\
        --upstream-model /path/to/model \\
        --bands 1 2 3 4 \\
        --requests 8 \\
        --output docs/validation/runtime-calibration.json
"""

