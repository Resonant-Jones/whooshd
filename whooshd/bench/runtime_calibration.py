@dataclass
class RequestOutcome:
    """Per-request measurement.

    Lifecycle timestamps come from the broker's own ``/runtime/requests``
    records — the harness never invents them.  ``broker_accepted_at`` is the
    broker's ``started_at`` (accepted) timestamp; ``broker_running_at`` is the
    broker's running transition timestamp when the broker exposes one.
    """

    ok: bool = False
    status_code: int = 0
    ttft_ms: Optional[float] = None
    latency_ms: float = 0.0
    completion_tokens: Optional[int] = None
    prompt_tokens: Optional[int] = None
    cached_prompt_tokens: Optional[int] = None
    upstream_prefill_ms: Optional[float] = None
    #: Client-side timestamp the request was issued.
    client_sent_at: Optional[float] = None
    #: Broker-reported accepted timestamp (Unix seconds).
    broker_accepted_at: Optional[float] = None
    #: Broker-reported running timestamp (Unix seconds), when exposed.
    broker_running_at: Optional[float] = None
    #: accepted -> running, in milliseconds, when both timestamps exist.
    queue_latency_ms: Optional[float] = None
    #: The broker's own lifecycle id for this request, when known.
    request_id: Optional[str] = None
    #: Whether the broker reports this request as having queued.
    queued: Optional[bool] = None
    error: Optional[str] = None


# ── Host metrics ───────────────────────────────────────────────────────────


def _swap_counters() -> Optional[dict[str, int]]:
    """Cumulative host swap counters, or None when they cannot be read.

    ``sysctl vm.swapusage`` is unavailable in some sandboxed sessions, but
    ``vm_stat`` reports cumulative ``Swapins``/``Swapouts`` page counts.
    Deltas across a band are the thrash signal: a band that swaps is a band
    that exceeded physical memory.
    """
    try:
        out = subprocess.run(
            ["vm_stat"], capture_output=True, text=True, timeout=10, check=False
        ).stdout
    except Exception:
        return None
    if not out:
        return None
    counters: dict[str, int] = {}
    for line in out.splitlines():
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip().lower()
        if key in ("swapins", "swapouts"):
            digits = value.strip().rstrip(".")
            try:
                counters[key] = int(digits)
            except ValueError:
                continue
    if "swapouts" not in counters:
        return None
    return counters


def _metal_status() -> dict[str, Any]:
    """Report whether this process can reach a Metal device.

    A calibration that cannot see the GPU is still useful when it is measured
    through a remote runtime, but the limitation must be recorded rather than
    hidden.
    """
    info: dict[str, Any] = {"metal_available": False, "detail": None}
    try:
        import mlx.core as mx  # type: ignore

        try:
            _ = mx.array([1.0])
            info["metal_available"] = True
            info["detail"] = str(mx.default_device())
        except Exception as exc:  # pragma: no cover - environment dependent
            info["detail"] = f"{type(exc).__name__}: {exc}"
    except Exception as exc:
        info["detail"] = f"mlx unavailable: {type(exc).__name__}"
    return info


# ── Helpers ────────────────────────────────────────────────────────────────


def _percentile(values: list[float], pct: float) -> Optional[float]:
    if not values:
        return None
    ordered = sorted(values)
    idx = max(0, min(len(ordered) - 1, int(math.ceil(pct / 100.0 * len(ordered))) - 1))
    return ordered[idx]


def _median(values: list[float]) -> Optional[float]:
    if not values:
        return None
    return statistics.median(values)


def _build_prompt(target_chars: int) -> str:
    """Synthetic prompt of approximately ``target_chars`` characters."""
    body = _PROMPT_BODY
    if target_chars <= len(body):
        return body[:target_chars]
    repeats = target_chars // len(body) + 1
    return (body * repeats)[:target_chars]


# ── Measurement ────────────────────────────────────────────────────────────


async def _measure_request(
    client: httpx.AsyncClient,
    *,
    base_url: str,
    model: str,
    prompt: str,
    max_tokens: int,
    timeout: float,
) -> RequestOutcome:
    """Measure one streaming request through the broker.

    A request counts as successful only when the response was 2xx **and** the
    stream carried the terminal ``[DONE]`` marker.  A 2xx stream that ends
    early, or that carries an SSE error frame, is a failure: it has no
    terminal completion and may never have produced a first token.
    """
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": prompt}],
        "stream": True,
        "max_tokens": max_tokens,
    }
    outcome = RequestOutcome()
    t0 = time.time()
    outcome.client_sent_at = t0
    saw_done = False
    saw_error_frame = False
    try:
        async with client.stream(
            "POST",
            f"{base_url}/v1/chat/completions",
            json=payload,
            timeout=timeout,
        ) as resp:
            outcome.status_code = resp.status_code
            outcome.request_id = resp.headers.get("X-Whoosh-Request-ID")
            outcome.queued = _provenance_queued(resp.headers)
            ttft: Optional[float] = None
            async for line in resp.aiter_lines():
                if not line.startswith("data: "):
                    continue
                data = line[6:].strip()
                if data == "[DONE]":
                    saw_done = True
                    break
                try:
                    chunk = json.loads(data)
                except json.JSONDecodeError:
                    continue
                if isinstance(chunk, dict) and chunk.get("error"):
                    # The broker reports mid-stream failures as an SSE error
                    # frame.  That is not a successful completion.
                    saw_error_frame = True
                    break
                delta = (chunk.get("choices") or [{}])[0].get("delta") or {}
                if delta.get("content") and ttft is None:
                    ttft = (time.time() - t0) * 1000
                usage = chunk.get("usage")
                if usage:
                    outcome.completion_tokens = usage.get("completion_tokens")
                    outcome.prompt_tokens = usage.get("prompt_tokens")
            outcome.ttft_ms = ttft
            outcome.latency_ms = (time.time() - t0) * 1000
            if saw_error_frame:
                outcome.error = "sse_error_frame"
            elif not saw_done and 200 <= outcome.status_code < 300:
                # A 2xx stream that never reached its terminal marker.
                outcome.error = "missing_terminal_done_marker"
            outcome.ok = (
                200 <= outcome.status_code < 300 and saw_done and not saw_error_frame
            )
    except Exception as exc:
        outcome.latency_ms = (time.time() - t0) * 1000
        outcome.error = f"{type(exc).__name__}"
    return outcome


async def _measure_non_streaming_request(
    client: httpx.AsyncClient,
    *,
    base_url: str,
    model: str,
    prompt: str,
    max_tokens: int,
    timeout: float,
) -> RequestOutcome:
    """Measure one non-streaming request through the broker.

    The broker's streaming chunks do not carry usage, so token accounting
    comes from the non-streaming response, which does.  Throughput is
    therefore measured on this path and latency on the streaming path.
    """
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": max_tokens,
    }
    outcome = RequestOutcome()
    t0 = time.time()
    outcome.client_sent_at = t0
    try:
        resp = await client.post(
            f"{base_url}/v1/chat/completions", json=payload, timeout=timeout
        )
        outcome.status_code = resp.status_code
        outcome.request_id = resp.headers.get("X-Whoosh-Request-ID")
        outcome.queued = _provenance_queued(resp.headers)
        if 200 <= resp.status_code < 300:
            body = resp.json()
            usage = body.get("usage") or {}
            outcome.prompt_tokens = usage.get("prompt_tokens")
            outcome.completion_tokens = usage.get("completion_tokens")
            details = usage.get("prompt_tokens_details") or {}
            if details.get("cached_tokens") is not None:
                outcome.cached_prompt_tokens = details.get("cached_tokens")
            provenance = body.get("runtime_provenance")
            if isinstance(provenance, dict) and isinstance(
                provenance.get("queued"), bool
            ):
                outcome.queued = provenance["queued"]
        outcome.latency_ms = (time.time() - t0) * 1000
        outcome.ok = 200 <= resp.status_code < 300
    except Exception as exc:
        outcome.latency_ms = (time.time() - t0) * 1000
        outcome.error = f"{type(exc).__name__}"
    return outcome


def _unavailable_cache_probe() -> dict[str, Any]:
    """An empty cache probe with the full result shape.

    Used when no upstream probe was configured or attempted.  Every counter
    is absent (``None``) rather than zero, so "not measured" never reads as
    "measured as zero".
    """
    return {
        "attempts": 0,
        "successful_attempts": 0,
        "failed_attempts": 0,
        "failure_reasons": [],
        "cached_prompt_tokens": None,
        "prompt_tokens": None,
        "prefill_ms": None,
        "cache_hit_ratio": None,
        "available": False,
    }


async def _probe_upstream_cache(
    client: httpx.AsyncClient,
    *,
    upstream_url: str,
    upstream_model: str,
    prompt: str,
    max_tokens: int,
    timeout: float,
    repeats: int = 2,
) -> dict[str, Any]:
    """Read upstream-reported prefill and prompt-cache counters.

    The upstream runtime is the same process the broker forwards to, so its
    cache counters describe the deployment's cache.  Returns measured numbers
    only; no prompt or generated text is retained.

    A probe is *available* only when the upstream answered with a success
    status **and** the payload carried valid usage data.  Failed attempts are
    counted and their reason recorded, but they never make the probe
    available and never contribute to the reported counters.
    """
    result: dict[str, Any] = _unavailable_cache_probe()
    payload = {
        "model": upstream_model,
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": max_tokens,
        "stream": False,
    }
    cached_total = 0
    prompt_total = 0
    prefills: list[float] = []
    for _ in range(max(1, repeats)):
        result["attempts"] += 1
        try:
            resp = await client.post(
                f"{upstream_url}/v1/chat/completions", json=payload, timeout=timeout
            )
        except Exception as exc:
            result["failed_attempts"] += 1
            result["failure_reasons"].append(f"transport_error:{type(exc).__name__}")
            continue
        if not (200 <= resp.status_code < 300):
            result["failed_attempts"] += 1
            result["failure_reasons"].append(f"http_status:{resp.status_code}")
            continue
        try:
            body = resp.json()
        except Exception:
            result["failed_attempts"] += 1
            result["failure_reasons"].append("invalid_json")
            continue
        if not isinstance(body, dict):
            result["failed_attempts"] += 1
            result["failure_reasons"].append("invalid_payload")
            continue
        usage = body.get("usage")
        if not isinstance(usage, dict) or not usage:
            # A 2xx error envelope or a payload without usage is not
            # measurement evidence.
            result["failed_attempts"] += 1
            result["failure_reasons"].append("missing_usage")
            continue
        result["successful_attempts"] += 1
        details = usage.get("prompt_tokens_details") or {}
        cached = details.get("cached_tokens")
        ptotal = usage.get("prompt_tokens")
        timings = body.get("timings") or {}
        if cached is not None:
            cached_total += int(cached)
        if ptotal is not None:
            prompt_total += int(ptotal)
        if timings.get("prompt_ms") is not None:
            prefills.append(float(timings["prompt_ms"]))
    if result["successful_attempts"]:
        result["available"] = True
        result["cached_prompt_tokens"] = cached_total
        result["prompt_tokens"] = prompt_total
        if prefills:
            result["prefill_ms"] = _median(prefills)
        if prompt_total:
            result["cache_hit_ratio"] = round(cached_total / prompt_total, 6)
    return result


async def _read_runtime_state(client: httpx.AsyncClient, base_url: str) -> dict[str, Any]:
    """Read leak-detection counters from the broker's own surfaces."""
    state: dict[str, Any] = {"active_jobs": None, "queue_depth": None, "reachable": False}
    try:
        resp = await client.get(f"{base_url}/runtime/admission", timeout=15.0)
        if resp.status_code == 200:
            body = resp.json()
            state["active_jobs"] = body.get("active_jobs")
            state["queue_depth"] = body.get("queue_depth")
            state["reachable"] = True
    except Exception:
        pass
    return state


async def _read_admission_counters(
    client: httpx.AsyncClient, base_url: str
) -> dict[str, Any]:
    """Read the broker's cumulative admission counters.

    Used to record whether requests actually entered the broker's queue
    during a band.  Counters only; never request content.
    """
    try:
        resp = await client.get(f"{base_url}/runtime/admission", timeout=15.0)
        if resp.status_code != 200:
            return {}
        body = resp.json()
        counters = body.get("counters")
        if not isinstance(counters, dict):
            return {}
        return {k: v for k, v in counters.items() if isinstance(v, int)}
    except Exception:
        return {}


async def _read_lifecycle_records(
    client: httpx.AsyncClient, base_url: str
) -> dict[str, dict[str, Any]]:
    """Read the broker's per-request lifecycle records, keyed by request id.

    Each record carries the broker's own accepted timestamp (``started_at``)
    and, when the broker exposes one, a running-transition timestamp.  The
    harness uses these verbatim — it never derives a lifecycle time from
    client-side observations.
    """
    try:
        resp = await client.get(f"{base_url}/runtime/requests", timeout=15.0)
        if resp.status_code != 200:
            return {}
        body = resp.json()
    except Exception:
        return {}
    records = body.get("requests")
    if not isinstance(records, list):
        return {}
    out: dict[str, dict[str, Any]] = {}
    for record in records:
        if not isinstance(record, dict):
            continue
        rid = record.get("request_id")
        if isinstance(rid, str) and rid:
            out[rid] = record
    return out


async def _run_band(
    client: httpx.AsyncClient,
    *,
    base_url: str,
    model: str,
    band: int,
    requests: int,
    prompt: str,
    max_tokens: int,
    timeout: float,
    upstream_url: Optional[str] = None,
    upstream_model: Optional[str] = None,
) -> tuple[BandEvidence, list[RequestOutcome]]:
    """Run one concurrency band and collect its evidence.

    The band bounds **simultaneous in-flight requests** to ``band`` in both
    measurement phases.  ``requests`` is the number of requests issued per
    band, not the concurrency: a band of x2 with 8 requests issues 8
    requests, two at a time.  The reported row therefore describes the
    concurrency that was actually exercised.
    """
    evidence = BandEvidence(concurrency=band)
    swap_before = _swap_counters()
    evidence.swap_used_pages_before = (
        swap_before.get("swapouts") if swap_before is not None else None
    )

    counters_before = await _read_admission_counters(client, base_url)

    limit = max(1, band)
    semaphore = asyncio.Semaphore(limit)
    in_flight = 0
    max_in_flight = 0

    async def _bounded(coro_factory):
        """Run one request, never exceeding ``band`` simultaneous requests."""
        nonlocal in_flight, max_in_flight
        async with semaphore:
            in_flight += 1
            max_in_flight = max(max_in_flight, in_flight)
            try:
                return await coro_factory()
            finally:
                in_flight -= 1

    # Phase A -- streaming: time to first token and end-to-end latency.
    outcomes = await asyncio.gather(
        *(
            _bounded(
                lambda: _measure_request(
                    client,
                    base_url=base_url,
                    model=model,
                    prompt=prompt,
                    max_tokens=max_tokens,
                    timeout=timeout,
                )
            )
            for _ in range(requests)
        )
    )

    # Phase B -- non-streaming: token accounting for throughput.  The broker
    # does not attach usage to streaming chunks, so throughput is measured
    # on the path that reports it.  This phase is bounded by the same band.
    token_started = time.time()
    token_outcomes = await asyncio.gather(
        *(
            _bounded(
                lambda: _measure_non_streaming_request(
                    client,
                    base_url=base_url,
                    model=model,
                    prompt=prompt,
                    max_tokens=max_tokens,
                    timeout=timeout,
                )
            )
            for _ in range(requests)
        )
    )
    token_wall = max(time.time() - token_started, 1e-6)

    evidence.request_count = requests
    evidence.max_in_flight = max_in_flight

    ttfts: list[float] = []
    latencies: list[float] = []
    for outcome in outcomes:
        if outcome.ok:
            evidence.success_count += 1
            if outcome.ttft_ms is not None:
                ttfts.append(outcome.ttft_ms)
            latencies.append(outcome.latency_ms)
        elif outcome.status_code == 429:
            evidence.overload_count += 1
        else:
            # Both transport failures and terminal-marker-less streams are
            # failures: neither produced a complete request.
            evidence.failure_count += 1

    evidence.ttft_p50_ms = _percentile(ttfts, 50)
    evidence.ttft_p95_ms = _percentile(ttfts, 95)
    evidence.latency_p50_ms = _percentile(latencies, 50)
    evidence.latency_p95_ms = _percentile(latencies, 95)

    # Throughput comes from the non-streaming phase, which reports usage.
    token_total = 0
    token_accounted = 0
    cached_total = 0
    cached_known = False
    for outcome in token_outcomes:
        if not outcome.ok:
            evidence.token_failure_count += 1
            if outcome.status_code == 429:
                evidence.overload_count += 1
            else:
                evidence.failure_count += 1
            continue
        evidence.token_success_count += 1
        if outcome.completion_tokens is None:
            evidence.token_unaccounted_count += 1
            continue
        token_accounted += 1
        token_total += outcome.completion_tokens
        if outcome.cached_prompt_tokens is not None:
            cached_known = True
            cached_total += outcome.cached_prompt_tokens

    evidence.token_request_count = requests
    token_phase_complete = (
        evidence.token_failure_count == 0
        and evidence.token_unaccounted_count == 0
        and evidence.token_success_count == requests
    )
    if token_phase_complete and token_accounted:
        seconds = max(token_wall, 1e-6)
        evidence.aggregate_tokens_per_second = round(token_total / seconds, 3)
        per_request_rates = []
        for outcome in token_outcomes:
            if outcome.ok and outcome.completion_tokens is not None:
                latency_s = max(outcome.latency_ms / 1000.0, 1e-6)
                per_request_rates.append(outcome.completion_tokens / latency_s)
        if per_request_rates:
            evidence.per_request_tokens_per_second = round(
                sum(per_request_rates) / len(per_request_rates), 3
            )
        if cached_known:
            evidence.cached_prompt_tokens = cached_total
    else:
        # Partial throughput is not evidence for the band.  Leave the
        # throughput fields unset rather than reporting the surviving subset.
        if evidence.token_failure_count:
            evidence.notes.append(
                "token accounting phase failed for "
                f"{evidence.token_failure_count} of {requests} requests; "
                "throughput not reported"
            )
        elif evidence.token_unaccounted_count:
            evidence.notes.append(
                "token usage unavailable from the runtime; throughput not measured"
            )
        else:
            evidence.notes.append(
                "token accounting phase did not complete; throughput not measured"
            )

    evidence.successful = (
        evidence.success_count == requests
        and evidence.failure_count == 0
        and evidence.overload_count == 0
        and evidence.stuck_count == 0
        and evidence.token_failure_count == 0
        and evidence.token_unaccounted_count == 0
        and evidence.token_success_count == requests
    )

    swap_after = _swap_counters()
    evidence.swap_used_pages_after = (
        swap_after.get("swapouts") if swap_after is not None else None
    )
    if swap_before is not None and swap_after is not None:
        evidence.swap_delta_pages = (
            swap_after.get("swapouts", 0) - swap_before.get("swapouts", 0)
        )
        evidence.swap_in_delta_pages = (
            swap_after.get("swapins", 0) - swap_before.get("swapins", 0)
        )
        if evidence.swap_delta_pages > 0:
            evidence.notes.append("host swapped pages during this band")

    # Cache counters and prefill cost come from the upstream runtime, which is
    # the same process — and therefore the same prompt cache — that the broker
    # forwards to.  The broker's own response shape does not expose them.
    if upstream_url and upstream_model:
        probe = await _probe_upstream_cache(
            client,
            upstream_url=upstream_url,
            upstream_model=upstream_model,
            prompt=prompt,
            max_tokens=max_tokens,
            timeout=timeout,
        )
        if probe.get("available"):
            evidence.cached_prompt_tokens = probe.get("cached_prompt_tokens")
            evidence.cache_hit_ratio = probe.get("cache_hit_ratio")
            evidence.prefill_p50_ms = probe.get("prefill_ms")
        else:
            reasons = ", ".join(probe.get("failure_reasons") or []) or "unknown"
            evidence.notes.append(
                "upstream cache probe unavailable "
                f"({probe.get('failed_attempts', 0)} failed attempt(s): {reasons})"
            )

    # Queue latency: the broker publishes lifecycle records over HTTP.  Their
    # accepted timestamp is authoritative; a running-transition timestamp is
    # only used when the broker actually publishes one.
    await _collect_queue_latency(
        client,
        base_url=base_url,
        evidence=evidence,
        outcomes=list(outcomes) + list(token_outcomes),
        counters_before=counters_before,
    )

    return evidence, outcomes


async def _collect_queue_latency(
    client: httpx.AsyncClient,
    *,
    base_url: str,
    evidence: BandEvidence,
    outcomes: list[RequestOutcome],
    counters_before: dict[str, Any],
) -> None:
    """Populate accepted -> running queue latency evidence for one band.

    Queue latency is measured **only** from timestamps the broker itself
    publishes.  The broker's lifecycle records expose the *accepted*
    timestamp for every request; they expose a *running-transition*
    timestamp only when the broker publishes one under a known field name.
    When it does not, queue latency is reported as unavailable with a
    reason — never as zero, and never synthesised from client-side timing.

    The evidence that *is* available is recorded either way: how many of this
    band's requests the broker reports as having queued, and the broker's own
    queue counter delta across the band.
    """
    counters_after = await _read_admission_counters(client, base_url)
    enqueued_before = counters_before.get("queued")
    enqueued_after = counters_after.get("queued")
    if isinstance(enqueued_before, int) and isinstance(enqueued_after, int):
        evidence.queue_enqueued_counter_delta = max(
            enqueued_after - enqueued_before, 0
        )

    # Per-request evidence, published by the broker on the response itself.
    queued_requests = sum(1 for o in outcomes if o.queued is True)
    if any(o.queued is not None for o in outcomes):
        evidence.queue_requests_enqueued = queued_requests

    records = await _read_lifecycle_records(client, base_url)
    latencies: list[float] = []
    accepted_seen = 0
    for outcome in outcomes:
        if not outcome.request_id:
            continue
        record = records.get(outcome.request_id)
        if not record:
            continue
        accepted = record.get("started_at")
        if isinstance(accepted, (int, float)) and not isinstance(accepted, bool):
            outcome.broker_accepted_at = float(accepted)
            accepted_seen += 1
        running = _running_timestamp(record)
        if running is None:
            continue
        outcome.broker_running_at = running
        if isinstance(accepted, (int, float)) and not isinstance(accepted, bool):
            delta_ms = (running - float(accepted)) * 1000.0
            outcome.queue_latency_ms = delta_ms
            latencies.append(delta_ms)

    evidence.queue_latency_samples = len(latencies)
    if latencies:
        evidence.queue_latency_p50_ms = _percentile(latencies, 50)
        evidence.queue_latency_p95_ms = _percentile(latencies, 95)
        evidence.queue_latency_available = True
        evidence.queue_latency_reason = None
        return

    evidence.queue_latency_available = False
    if accepted_seen == 0:
        evidence.queue_latency_reason = (
            "broker published no matching lifecycle records for this band's "
            "requests; accepted->running queue latency could not be measured"
        )
    else:
        evidence.queue_latency_reason = (
            "broker publishes accepted timestamps but no running-transition "
            "timestamp, so accepted->running queue latency cannot be measured"
        )
    evidence.notes.append(evidence.queue_latency_reason)


def _provenance_queued(headers: Any) -> Optional[bool]:
    """Read the broker's ``queued`` flag from its runtime provenance.

    The broker publishes bounded runtime provenance (including whether the
    request was queued) as a response header on the streaming path.  A
    missing or unparsable provenance yields ``None`` — "not reported" — not
    ``False``.
    """
    raw = headers.get(WHOOSHD_RUNTIME_PROVENANCE_HEADER)
    if not raw:
        return None
    try:
        payload = json.loads(raw)
    except (TypeError, ValueError):
        return None
    if not isinstance(payload, dict):
        return None
    queued = payload.get("queued")
    if isinstance(queued, bool):
        return queued
    return None


def _running_timestamp(record: dict[str, Any]) -> Optional[float]:
    """Return the broker's running-transition timestamp, when published.

    The broker's lifecycle record names the accepted timestamp ``started_at``.
    A running-transition timestamp is optional: it is read only when the
    broker actually publishes one under one of the known field names.
    """
    for key in ("running_at", "running_started_at", "started_running_at"):
        value = record.get(key)
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return float(value)
    return None


# ── Report assembly ────────────────────────────────────────────────────────


def _build_report(
    *,
    base_url: str,
    upstream_url: Optional[str],
    model: str,
    bands: list[BandEvidence],
    cache_probe: dict[str, Any],
    rest_state: dict[str, Any],
    prompt_chars: int,
    max_tokens: int,
) -> dict[str, Any]:
    return {
        "schema_version": "whooshd.calibration.v1",
        "captured_at": datetime.now(timezone.utc).isoformat(),
        "host": {
            "platform": platform.platform(),
            "machine": platform.machine(),
            "python": platform.python_version(),
        },
        "target": {
            "base_url": base_url,
            "upstream_url": upstream_url,
            "model": model,
            "prompt_chars": prompt_chars,
            "max_tokens": max_tokens,
        },
        "metal": _metal_status(),
        "bands": [b.safe_dict() for b in bands],
        "cache_effectiveness": cache_probe,
        "leak_check": _leak_check(rest_state),
    }


def _leak_check(rest_state: dict[str, Any]) -> dict[str, Any]:
    """Build the at-rest leak check.

    ``leaked`` is ``None`` — meaning *unknown* — whenever the broker was
    unreachable or either counter was unavailable.  An unmeasured final state
    is never reported as an affirmative "no leak" result.
    """
    reachable = bool(rest_state.get("reachable"))
    active_jobs = rest_state.get("active_jobs")
    queue_depth = rest_state.get("queue_depth")
    counters_known = (
        isinstance(active_jobs, int)
        and not isinstance(active_jobs, bool)
        and isinstance(queue_depth, int)
        and not isinstance(queue_depth, bool)
    )
    if not reachable:
        status = "unknown"
        reason = "broker was unreachable at the final leak check"
        leaked: Optional[bool] = None
    elif not counters_known:
        status = "unknown"
        reason = "broker did not report both lifecycle counters at the final leak check"
        leaked = None
    else:
        leaked = active_jobs > 0 or queue_depth > 0
        status = "leaked" if leaked else "clean"
        reason = None
    return {
        "active_jobs_at_rest": active_jobs,
        "queue_depth_at_rest": queue_depth,
        "broker_reachable": reachable,
        "leaked": leaked,
        "status": status,
        "reason": reason,
    }


def _render_markdown(report: dict[str, Any]) -> str:
    lines: list[str] = []
    add = lines.append

    def fmt(value: Optional[float], suffix: str = "") -> str:
        if value is None:
            return "—"
        if suffix:
            return f"{value:.1f}{suffix}"
        return f"{value:.1f}"

    add("# Runtime Calibration Report")
    add("")
    add(f"**Schema:** `{report['schema_version']}`  ")
    add(f"**Captured:** {report['captured_at']}  ")
    add(f"**Host:** {report['host']['platform']}  ")
    add(f"**Metal in harness process:** {report['metal']['metal_available']} "
        f"({report['metal']['detail']})")
    add("")
    add(f"**Target:** `{report['target']['base_url']}` model `{report['target']['model']}` "
        f"prompt {report['target']['prompt_chars']} chars, "
        f"max_tokens {report['target']['max_tokens']}")
    add("")
    add("## Concurrency bands")
    add("")
    add("| Band | In flight | OK | 429 | Fail | Tok fail | TTFT p50 | TTFT p95 | "
        "Lat p50 | Prefill p50 | Agg tok/s | Queue p50 | Swap Δ |")
    add("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for band in report["bands"]:
        add(
            f"| x{band['concurrency']} | {band.get('max_in_flight', '—')} "
            f"| {band['success_count']}/{band['request_count']} "
            f"| {band['overload_count']} | {band['failure_count']} "
            f"| {band.get('token_failure_count', '—')} "
            f"| {fmt(band.get('ttft_p50_ms'))} | {fmt(band.get('ttft_p95_ms'))} "
            f"| {fmt(band.get('latency_p50_ms'))} | {fmt(band.get('prefill_p50_ms'))} "
            f"| {fmt(band.get('aggregate_tokens_per_second'))} "
            f"| {fmt(band.get('queue_latency_p50_ms'))} "
            f"| {band['swap_delta_pages'] if band['swap_delta_pages'] is not None else '—'} |"
        )
    add("")
    add("A band is successful only when the streaming phase **and** the "
        "token-accounting phase both completed for every request.")
    add("")
    for band in report["bands"]:
        for note in band.get("notes") or []:
            add(f"- x{band['concurrency']}: {note}")
    if any(band.get("notes") for band in report["bands"]):
        add("")
    cache = report.get("cache_effectiveness") or {}
    add("## Cache effectiveness")
    add("")
    add(f"- Upstream cache counters available: **{cache.get('available', False)}**")
    add(f"- Cached prompt tokens: **{cache.get('cached_prompt_tokens')}**")
    add(f"- Prompt tokens: **{cache.get('prompt_tokens')}**")
    add(f"- Cache hit ratio: **{cache.get('cache_hit_ratio')}**")
    add(f"- Upstream-reported prefill (ms): **{cache.get('prefill_ms')}**")
    add(f"- Successful probes: **{cache.get('successful_attempts', 0)}**")
    add(f"- Failed probes: **{cache.get('failed_attempts', 0)}**")
    reasons = cache.get("failure_reasons") or []
    if reasons:
        add(f"- Probe failure reasons: **{', '.join(str(r) for r in reasons)}**")
    add("")
    leak = report.get("leak_check") or {}
    add("## Leak check (at rest)")
    add("")
    add(f"- `active_jobs` at rest: **{leak.get('active_jobs_at_rest')}**")
    add(f"- `queue_depth` at rest: **{leak.get('queue_depth_at_rest')}**")
    leaked = leak.get("leaked")
    if leaked is None:
        add(f"- Leaked work: **unknown**")
        if leak.get("reason"):
            add(f"- Reason: {leak['reason']}")
    else:
        add(f"- Leaked work: **{leaked}**")
    add("")
    return "\n".join(lines)


# ── CLI ────────────────────────────────────────────────────────────────────


def _parse_args(argv: Optional[list[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="python -m whooshd.bench.runtime_calibration",
        description="Real-runtime calibration harness for a live Whoosh'd deployment.",
    )
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--upstream-url", default=None,
                        help="Upstream runtime base URL (for prefill/cache counters)")
    parser.add_argument("--upstream-model", default=None,
                        help="Model id understood by the upstream runtime")
    parser.add_argument("--model", default="local-chat")
    parser.add_argument("--bands", type=int, nargs="+", default=list(DEFAULT_BANDS))
    parser.add_argument("--requests", type=int, default=DEFAULT_REQUESTS_PER_BAND)
    parser.add_argument("--timeout", type=float, default=DEFAULT_TIMEOUT_SECONDS)
    parser.add_argument("--max-tokens", type=int, default=DEFAULT_MAX_TOKENS)
    parser.add_argument("--prompt-chars", type=int, default=2048)
    parser.add_argument("--output", default="runtime-calibration.json")
    parser.add_argument("--markdown", default=None, help="Optional markdown summary path")
    return parser.parse_args(argv)


def main(argv: Optional[list[str]] = None) -> int:
    args = _parse_args(argv)
    prompt = _build_prompt(args.prompt_chars)

    async def run() -> int:
        limits = httpx.Limits(max_connections=32, max_keepalive_connections=16)
        async with httpx.AsyncClient(limits=limits) as client:
            state = await _read_runtime_state(client, args.base_url)
            if not state.get("reachable"):
                print(
                    "BLOCKED: broker not reachable at "
                    f"{args.base_url}/runtime/admission",
                    file=sys.stderr,
                )
                return 2

            bands: list[BandEvidence] = []
            for band in args.bands:
                evidence, _ = await _run_band(
                    client,
                    base_url=args.base_url,
                    model=args.model,
                    band=band,
                    requests=args.requests,
                    prompt=prompt,
                    max_tokens=args.max_tokens,
                    timeout=args.timeout,
                    upstream_url=args.upstream_url,
                    upstream_model=args.upstream_model,
                )
                bands.append(evidence)
                print(
                    f"band x{band}: ok={evidence.success_count}/{evidence.request_count} "
                    f"ttft_p50={evidence.ttft_p50_ms} lat_p50={evidence.latency_p50_ms}",
                    file=sys.stderr,
                )

            # When no upstream probe is configured the cache counters are
            # *unavailable*, not zero.  The dict keeps the full shape so the
            # optional markdown path can render it without missing keys.
            cache_probe: dict[str, Any] = _unavailable_cache_probe()
            if args.upstream_url and args.upstream_model:
                cache_probe = await _probe_upstream_cache(
                    client,
                    upstream_url=args.upstream_url,
                    upstream_model=args.upstream_model,
                    prompt=prompt,
                    max_tokens=args.max_tokens,
                    timeout=args.timeout,
                )
            else:
                cache_probe["failure_reasons"] = ["no_upstream_configured"]

            rest_state = await _read_runtime_state(client, args.base_url)

        report = _build_report(
            base_url=args.base_url,
            upstream_url=args.upstream_url,
            model=args.model,
            bands=bands,
            cache_probe=cache_probe,
            rest_state=rest_state,
            prompt_chars=len(prompt),
            max_tokens=args.max_tokens,
        )
        os.makedirs(os.path.dirname(os.path.abspath(args.output)) or ".", exist_ok=True)
        with open(args.output, "w", encoding="utf-8") as handle:
            json.dump(report, handle, indent=2, sort_keys=True)
            handle.write("\n")
        if args.markdown:
            os.makedirs(os.path.dirname(os.path.abspath(args.markdown)) or ".", exist_ok=True)
            with open(args.markdown, "w", encoding="utf-8") as handle:
                handle.write(_render_markdown(report))
        print(f"wrote {args.output}")
        return 0

    return asyncio.run(run())


if __name__ == "__main__":
    raise SystemExit(main())
